/** The native type realizing `kind` on `provider`, or undefined when the provider cannot host it. */
export function nativeTypeFor(provider: string, kind: PortableKind): string | undefined {
  return NATIVE_TYPES[provider]?.[kind];
}

/** Providers the catalog and solver know about, sorted. */
export function placementProviders(): string[] {
  return Object.keys(NATIVE_TYPES).sort();
}

