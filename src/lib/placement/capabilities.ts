/**
 * Which provider hosts which portable kind, and which catalog SKU prices which
 * cost role (ADR-0013, ADR-0003).
 *
 * `NATIVE_TYPES` uses the Level-2 vocabulary of `@/lib/resources/types`
 * (`aws:ecs_service`, `gcp:cloud_run_service`, ...). It is the placement
 * solver's capability table: a kind with no entry for a provider means the
 * provider cannot host it natively and the candidate is rejected with that
 * reason. Entries here are placement/cost knowledge; whether a driver for the
 * native type exists is decided elsewhere (drivers registry), so a candidate
 * can be cost-feasible on a provider whose driver is not written yet. The
 * solver reports that as a warning rather than pretending otherwise.
 *
 * `SKU_ROLES` maps a provider-agnostic cost role to that provider's catalog
 * SKU. Roles that a provider does not have (for example `lb_capacity_unit_hour`
 * on GCP, which meters processed GB instead) are simply absent.
 */
